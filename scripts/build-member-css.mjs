#!/usr/bin/env node
// Generates app/member/member-ui.css from the approved designs in docs/design/*.html.
// Each design's <style> is complete and self-contained, so every page gets its OWN copy of its CSS,
// scoped under `.m8.m8-<page>` (what the approved design looks like, by construction).
// Nothing is global: no :root, no html/body, no `*` outside the wrapper. Run: node scripts/build-member-css.mjs
import fs from 'node:fs'
import path from 'node:path'
import postcss from 'postcss'

const DESIGN_DIR = 'docs/design'
const OUT = 'app/member/member-ui.css'
const PAGES = {
  wallet:  { file: 'space-wallet.html',          body: true  },
  points:  { file: 'space-points.html',          body: true  },
  inbox:   { file: 'space-inbox.html',           body: true  },
  // quick-action tiles live INSIDE the existing /member home page: never style the page itself
  actions: { file: 'member-quick-actions.html',  body: false },
}
// rules that only exist for the review file, not for the product
const REVIEW_ONLY = /^(\.review\b|#spec\b|#specBtn\b|\.frame\b|\.frame-t\b|\.note\b|pre$|\.wrap$)/

function scopePlugin(wrapper, keepBody) {
  return {
    postcssPlugin: 'm8-scope',
    Once(root) {
      root.walkAtRules('font-face', (r) => r.remove())          // font is declared once, below
      root.walkRules((rule) => {
        const p = rule.parent
        if (p && p.type === 'atrule' && /keyframes$/.test(p.name)) return
        const out = []
        for (let sel of rule.selectors) {
          sel = sel.trim()
          if (REVIEW_ONLY.test(sel)) continue
          if (sel === ':root') { out.push(wrapper); continue }
          if (sel === 'html') continue
          if (sel === 'body' || sel.startsWith('body ')) { if (keepBody) out.push(sel.replace(/^body/, wrapper)); continue }
          if (sel === '*') { out.push(`${wrapper} *`); continue }
          out.push(`${wrapper} ${sel}`)
        }
        if (out.length) rule.selectors = out; else rule.remove()
      })
      // keyframe names are global: prefix them per page so pages cannot collide
      const names = new Set()
      root.walkAtRules(/keyframes$/, (r) => { names.add(r.params); r.params = `m8-${wrapper.replace(/[^a-z-]/g, '')}-${r.params}` })
      root.walkDecls(/^animation(-name)?$/, (d) => { for (const n of names) d.value = d.value.replace(new RegExp(`\\b${n}\\b`, 'g'), `m8-${wrapper.replace(/[^a-z-]/g, '')}-${n}`) })
    },
  }
}
scopePlugin.postcss = true

let css = `/* GENERATED by scripts/build-member-css.mjs from docs/design/*.html — do not edit by hand.
 * Every rule is scoped under .m8.m8-<page>. Wrap each page: <div className="m8 m8-wallet"> ... </div> */
@font-face{font-family:'Good Times';src:url('/fonts/GOODTIME.TTF') format('truetype');font-weight:400;font-style:normal;font-display:swap}
`
for (const [name, cfg] of Object.entries(PAGES)) {
  const html = fs.readFileSync(path.join(DESIGN_DIR, cfg.file), 'utf8')
  const style = html.match(/<style>([\s\S]*?)<\/style>/)?.[1]
  if (!style) throw new Error(`no <style> in ${cfg.file}`)
  const wrapper = `.m8.m8-${name}`
  const res = await postcss([scopePlugin(wrapper, cfg.body)]).process(style, { from: undefined })
  css += `\n/* ===== ${name} ===== */\n${res.css}\n`
}
// the wrapper behaves like the design's <body>: full height; the sticky offset has no review bar in the product
css = css.replace(/--stick:49px/g, '--stick:0px')
fs.writeFileSync(OUT, css)
console.log(`${OUT}: ${css.length} bytes`)
